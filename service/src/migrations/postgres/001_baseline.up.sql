-- PostgreSQL baseline for the team profile. It represents the schema produced by the SQLite
-- migrations 001 to 013. New migrations are added to both dialects after this baseline.
-- Emails are stored lowercase by the application; a unique index on lower(email) keeps the
-- case-insensitive uniqueness of the SQLite schema without requiring the citext extension.

CREATE TABLE accounts (
    id TEXT PRIMARY KEY,
    email TEXT NOT NULL,
    display_name TEXT NOT NULL,
    password_hash TEXT,
    email_verified_at BIGINT,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    deleted_at BIGINT,
    deletion_requested_at BIGINT,
    deletion_due_at BIGINT,
    totp_secret TEXT,
    totp_enabled_at BIGINT,
    username TEXT,
    first_name TEXT,
    last_name TEXT,
    avatar_color TEXT,
    avatar_url TEXT,
    role TEXT NOT NULL DEFAULT 'member' CHECK (role IN ('admin', 'member')),
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'disabled'))
);
CREATE UNIQUE INDEX accounts_email_unique ON accounts (lower(email));
CREATE UNIQUE INDEX accounts_username_unique ON accounts (lower(username))
    WHERE username IS NOT NULL;

CREATE TABLE sessions (
    id TEXT PRIMARY KEY,
    account_id TEXT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    token_hash TEXT NOT NULL UNIQUE,
    family_id TEXT NOT NULL,
    device_label TEXT,
    created_at BIGINT NOT NULL,
    last_seen_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL,
    revoked_at BIGINT,
    ip_hash TEXT,
    user_agent TEXT,
    csrf_hash TEXT
);
CREATE INDEX sessions_account ON sessions(account_id);
CREATE INDEX sessions_family ON sessions(family_id);

CREATE TABLE refresh_tokens (
    id TEXT PRIMARY KEY,
    session_id TEXT NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
    token_hash TEXT NOT NULL UNIQUE,
    created_at BIGINT NOT NULL,
    used_at BIGINT,
    replaced_by TEXT,
    revoked_at BIGINT
);
CREATE INDEX refresh_tokens_session ON refresh_tokens(session_id);

CREATE TABLE access_tokens (
    id TEXT PRIMARY KEY,
    session_id TEXT NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
    token_hash TEXT NOT NULL UNIQUE,
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL,
    revoked_at BIGINT
);
CREATE INDEX access_tokens_session ON access_tokens(session_id);
CREATE INDEX access_tokens_expires ON access_tokens(expires_at);

CREATE TABLE email_tokens (
    id TEXT PRIMARY KEY,
    account_id TEXT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    kind TEXT NOT NULL CHECK (kind IN ('verify', 'reset')),
    token_hash TEXT NOT NULL UNIQUE,
    expires_at BIGINT NOT NULL,
    used_at BIGINT,
    created_at BIGINT NOT NULL
);
CREATE INDEX email_tokens_account ON email_tokens(account_id, kind);

CREATE TABLE login_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email_hash TEXT NOT NULL,
    ip_hash TEXT NOT NULL,
    success INTEGER NOT NULL,
    created_at BIGINT NOT NULL
);
CREATE INDEX login_attempts_email ON login_attempts(email_hash, created_at);
CREATE INDEX login_attempts_ip ON login_attempts(ip_hash, created_at);

CREATE TABLE api_tokens (
    id TEXT PRIMARY KEY,
    account_id TEXT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    scopes TEXT NOT NULL,
    token_hash TEXT NOT NULL UNIQUE,
    created_at BIGINT NOT NULL,
    expires_at BIGINT,
    revoked_at BIGINT
);
CREATE INDEX api_tokens_account ON api_tokens(account_id);

CREATE TABLE projects (
    id TEXT PRIMARY KEY,
    owner_account_id TEXT NOT NULL REFERENCES accounts(id),
    name TEXT NOT NULL,
    sync_enabled INTEGER NOT NULL DEFAULT 0,
    revision INTEGER NOT NULL DEFAULT 1,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    deleted_at BIGINT,
    public_sharing_enabled INTEGER NOT NULL DEFAULT 0,
    parent_project_id TEXT REFERENCES projects(id)
);
CREATE INDEX projects_owner ON projects(owner_account_id);
CREATE INDEX projects_parent ON projects(parent_project_id);

CREATE TABLE project_members (
    project_id TEXT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    account_id TEXT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    role TEXT NOT NULL CHECK (role IN ('owner', 'editor', 'commenter', 'viewer')),
    created_at BIGINT NOT NULL,
    PRIMARY KEY (project_id, account_id)
);
CREATE INDEX project_members_account ON project_members(account_id);

CREATE TABLE project_snapshots (
    project_id TEXT PRIMARY KEY REFERENCES projects(id) ON DELETE CASCADE,
    revision INTEGER NOT NULL,
    doc TEXT NOT NULL,
    updated_by TEXT REFERENCES accounts(id),
    updated_at BIGINT NOT NULL
);

CREATE TABLE audit_log (
    id TEXT PRIMARY KEY,
    actor_account_id TEXT REFERENCES accounts(id) ON DELETE SET NULL,
    action TEXT NOT NULL,
    resource_type TEXT NOT NULL,
    resource_id TEXT,
    ip_hash TEXT,
    metadata TEXT,
    created_at BIGINT NOT NULL
);
CREATE INDEX audit_log_created ON audit_log(created_at);
CREATE INDEX audit_log_resource ON audit_log(resource_type, resource_id);

CREATE TABLE objects (
    id TEXT PRIMARY KEY,
    sha256 TEXT NOT NULL UNIQUE,
    bytes INTEGER NOT NULL,
    content_type TEXT NOT NULL,
    storage_key TEXT NOT NULL UNIQUE,
    created_at BIGINT NOT NULL
);

CREATE TABLE service_meta (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

CREATE TABLE project_invitations (
    id TEXT PRIMARY KEY,
    project_id TEXT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    email TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('editor', 'commenter', 'viewer')),
    token_hash TEXT NOT NULL UNIQUE,
    invited_by TEXT REFERENCES accounts(id) ON DELETE SET NULL,
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL,
    accepted_at BIGINT,
    revoked_at BIGINT
);
CREATE INDEX project_invitations_project ON project_invitations(project_id);
CREATE INDEX project_invitations_email ON project_invitations(email);

CREATE TABLE share_links (
    id TEXT PRIMARY KEY,
    project_id TEXT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    scope TEXT NOT NULL CHECK (scope IN ('project', 'item', 'column')),
    target_id TEXT,
    permission TEXT NOT NULL CHECK (permission IN ('view', 'comment', 'edit', 'manage')),
    token_hash TEXT NOT NULL UNIQUE,
    password_hash TEXT,
    download_allowed INTEGER NOT NULL DEFAULT 0,
    created_by TEXT REFERENCES accounts(id) ON DELETE SET NULL,
    created_at BIGINT NOT NULL,
    expires_at BIGINT,
    revoked_at BIGINT,
    last_accessed_at BIGINT
);
CREATE INDEX share_links_project ON share_links(project_id);
CREATE INDEX share_links_target ON share_links(project_id, target_id);

CREATE TABLE share_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    share_id TEXT NOT NULL REFERENCES share_links(id) ON DELETE CASCADE,
    ip_hash TEXT NOT NULL,
    success INTEGER NOT NULL,
    created_at BIGINT NOT NULL
);
CREATE INDEX share_attempts_link ON share_attempts(share_id, ip_hash, created_at);

CREATE TABLE email_otps (
    id TEXT PRIMARY KEY,
    account_id TEXT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    code_hash TEXT NOT NULL,
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL,
    used_at BIGINT,
    attempts INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX email_otps_account ON email_otps(account_id, created_at);

CREATE TABLE abuse_reports (
    id TEXT PRIMARY KEY,
    share_id TEXT NOT NULL REFERENCES share_links(id) ON DELETE CASCADE,
    reason TEXT NOT NULL,
    reporter_ip_hash TEXT,
    created_at BIGINT NOT NULL,
    status TEXT NOT NULL DEFAULT 'open'
);
CREATE INDEX abuse_reports_share ON abuse_reports(share_id);

CREATE TABLE project_assets (
    id TEXT PRIMARY KEY,
    project_id TEXT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    object_id TEXT NOT NULL REFERENCES objects(id),
    name TEXT NOT NULL,
    content_type TEXT NOT NULL,
    bytes INTEGER NOT NULL,
    created_by TEXT REFERENCES accounts(id) ON DELETE SET NULL,
    created_at BIGINT NOT NULL
);
CREATE INDEX project_assets_project ON project_assets(project_id, created_at);

CREATE TABLE project_versions (
    id TEXT PRIMARY KEY,
    project_id TEXT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    revision INTEGER NOT NULL,
    doc TEXT NOT NULL,
    created_by TEXT REFERENCES accounts(id) ON DELETE SET NULL,
    created_at BIGINT NOT NULL,
    UNIQUE (project_id, revision)
);
CREATE INDEX project_versions_project ON project_versions(project_id, revision DESC);

CREATE TABLE notifications (
    id TEXT PRIMARY KEY,
    account_id TEXT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    kind TEXT NOT NULL,
    title TEXT NOT NULL,
    body TEXT,
    resource_type TEXT NOT NULL,
    resource_id TEXT NOT NULL,
    created_at BIGINT NOT NULL,
    read_at BIGINT
);
CREATE INDEX notifications_account ON notifications(account_id, created_at DESC);
CREATE INDEX notifications_resource ON notifications(resource_type, resource_id);

CREATE TABLE email_preferences (
    account_id TEXT PRIMARY KEY REFERENCES accounts(id) ON DELETE CASCADE,
    notifications INTEGER NOT NULL DEFAULT 0,
    last_notified_at BIGINT,
    updated_at BIGINT NOT NULL,
    presence_enabled INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE passkey_credentials (
    id TEXT PRIMARY KEY,
    account_id TEXT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    public_key TEXT NOT NULL,
    counter INTEGER NOT NULL DEFAULT 0,
    transports TEXT,
    device_type TEXT,
    backed_up INTEGER NOT NULL DEFAULT 0,
    name TEXT NOT NULL DEFAULT 'Passkey',
    created_at BIGINT NOT NULL,
    last_used_at BIGINT
);
CREATE INDEX passkey_credentials_account ON passkey_credentials(account_id);

CREATE TABLE passkey_challenges (
    id TEXT PRIMARY KEY,
    challenge TEXT NOT NULL UNIQUE,
    email TEXT NOT NULL,
    account_id TEXT REFERENCES accounts(id) ON DELETE CASCADE,
    kind TEXT NOT NULL CHECK (kind IN ('register', 'login')),
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL
);
CREATE INDEX passkey_challenges_email ON passkey_challenges(email, kind, created_at);

CREATE TABLE email_jobs (
    id TEXT PRIMARY KEY,
    to_address TEXT NOT NULL,
    subject TEXT NOT NULL,
    body TEXT NOT NULL,
    kind TEXT NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    last_error TEXT,
    next_at BIGINT NOT NULL,
    created_at BIGINT NOT NULL,
    sent_at BIGINT
);
CREATE INDEX email_jobs_due ON email_jobs(sent_at, next_at);
