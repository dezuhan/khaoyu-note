const locales = { en, "pt-BR": ptBR, id, es, fr, de, ja, ko, "zh-CN": zhCN, ru };

export function initLanguage() {
  document.documentElement.lang = getLanguage();
}

export function getLanguage() {
  try {
    const stored = localStorage.getItem("mn.language") || "en";
    return LANGUAGES.some((language) => language.id === stored) ? stored : "en";
  } catch {
    return "en";
  }
}

export function setLanguage(id) {
  if (!LANGUAGES.some((language) => language.id === id)) return false;
  try {
    localStorage.setItem("mn.language", id);
  } catch {
    /* private mode */
  }
  document.documentElement.lang = id;
  window.dispatchEvent(new CustomEvent("mn:language-changed", { detail: { language: id } }));
  return true;
}

export function translationKeys() {
  return [
    ...Object.keys(en),
    ...Object.keys(toolNames.en).map((key) => `tool.${key}`),
    ...Object.keys(uiNames.en).map((key) => `topbar.${key}`),
    ...Object.keys(pageText.en),
    ...Object.keys(migrationText.en),
    ...Object.keys(statsText.en),
    ...Object.keys(templateDeleteText.en),
    ...Object.keys(menuText.en),
    ...Object.keys(actionText.en).map((text) => `action.${text}`),
    ...Object.keys(aboutText.en),
  ];
}

export function hasTranslation(language, key) {
  if (key === "nav.mcp") return true;
  if (key.startsWith("tool.")) return Boolean(toolNames[language]?.[key.slice(5)]);
  if (key.startsWith("topbar.")) return Boolean(uiNames[language]?.[key.slice(7)]);
  if (key.startsWith("backup.")) return Boolean(migrationText[language]?.[key] || pageText[language]?.[key]);
  if (key.startsWith("stats.")) return Boolean(statsText[language]?.[key]);
  if (key.startsWith("templateDelete.")) return Boolean(templateDeleteText[language]?.[key]);
  if (key.startsWith("menu.")) return Boolean(menuText[language]?.[key]);
  if (key.startsWith("action.")) return Boolean(actionText[language]?.[key.slice(7)]);
  if (key.startsWith("about.")) return Boolean(aboutText[language]?.[key]);
  return Boolean(locales[language]?.[key]);
}

export function translateActionText(text) {
  const language = getLanguage();
  return actionText[language]?.[text] || text;
}

export function t(key, fallback = "") {
  const language = getLanguage();
  if (key.startsWith("tool.")) {
    const name = key.slice(5);
    return toolNames[language]?.[name] || toolNames.en[name] || fallback || key;
  }
  if (key.startsWith("topbar.")) {
    const name = key.slice(7);
    return uiNames[language]?.[name] || uiNames.en[name] || fallback || key;
  }
  if (key.startsWith("backup.")) {
    return migrationText[language]?.[key] || migrationText.en[key] || pageText[language]?.[key] || pageText.en[key] || fallback || key;
  }
  if (key.startsWith("stats.")) {
    return statsText[language]?.[key] || statsText.en[key] || fallback || key;
  }
  if (key.startsWith("templateDelete.")) {
    return templateDeleteText[language]?.[key] || templateDeleteText.en[key] || fallback || key;
  }
  if (key.startsWith("menu.")) {
    return menuText[language]?.[key] || menuText.en[key] || fallback || key;
  }
  if (key.startsWith("action.")) {
    const text = key.slice(7);
    return actionText[language]?.[text] || actionText.en[text] || fallback || text;
  }
  if (key.startsWith("about.")) {
    return aboutText[language]?.[key] || aboutText.en[key] || fallback || key;
  }
  return locales[language]?.[key] || en[key] || fallback || key;
}
